// Notas que el auditor escribe en español en los JSON.
export function translateNote(note, lang) {
  if (lang !== "en") return note;
  return note
    .replace(/^Lighthouse \((mobile|desktop)\): (\d+) de (\d+) corridas no pudieron analizar la página$/, "Lighthouse ($1): $2 of $3 runs could not analyze the page")
    .replace(/^no se pudo leer robots\.txt; se omite por prudencia$/, "robots.txt could not be read; skipped out of caution")
    .replace(/^robots\.txt no permite visitar la página de inicio$/, "robots.txt disallows the homepage")
    .replace(/: la página no terminó de cargar a tiempo$/, ": the page did not finish loading in time")
    .replace(/: no se pudo conectar con el sitio$/, ": could not connect to the site")
    .replace(/: no se pudo cargar la página$/, ": the page could not be loaded")
    .replace(/^inicio \((escritorio|móvil)\)/, (_, v) => `homepage (${v === "móvil" ? "mobile" : "desktop"})`)
    .replace(/^página interna/, "internal page");
}
